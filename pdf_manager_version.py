"""Application version, derived from the Git tag (e.g. ``v1.2.3`` -> ``1.2.3``).

Release builds embed the tag in ``_build_version.py`` (generated by
``scripts/build_application.py``). From a source checkout, ``git describe`` is used, or
the commit date and hash (``0.0.0+<date>.<hash>``) when no tag is reachable.
"""
import subprocess
from pathlib import Path

UNKNOWN_VERSION = "0.0.0+unknown"


def normalize_version(raw):
    return raw.strip().removeprefix("v")


def _git(*arguments):
    try:
        result = subprocess.run(
            ["git", *arguments],
            cwd=Path(__file__).resolve().parent,
            capture_output=True,
            text=True,
            timeout=5,
            check=True,
        )
    except (OSError, subprocess.SubprocessError):
        return None
    return result.stdout.strip() or None


def _git_version():
    tagged = _git("describe", "--tags", "--match", "v*", "--dirty")
    if tagged:
        return normalize_version(tagged)
    # No tag reachable: fall back to commit date and short hash.
    commit = _git(
        "show", "-s", "--format=%cd.%h", "--date=format-local:%Y%m%d%H%M%S", "HEAD"
    )
    return f"0.0.0+{commit}" if commit else None


def _resolve_version():
    try:
        from _build_version import VERSION
    except ImportError:
        return _git_version() or UNKNOWN_VERSION
    return VERSION


__version__ = _resolve_version()
